def compute_validation_table(exp_dir="CV/allunmappedglaciers_notsurging"):
    device = torch.device('cuda:0' if torch.cuda.is_available() else 'cpu')
    mape_metric = MeanAbsolutePercentageError().to(device)

    rows = []

    for rgi_id in GLACIER_IDS:
        # 1. Locate checkpoint and config for this glacier fold
        fold_dirs = glob.glob(os.path.join(exp_dir, f"*{rgi_id}*"))
        if not fold_dirs:
            # Fallback search recursive
            fold_dirs = glob.glob(os.path.join(exp_dir, "**", f"*{rgi_id}*"), recursive=True)

        if not fold_dirs:
            print(f"Skipping {rgi_id}: No fold directory found.")
            continue

        fold_dir = sorted(fold_dirs, key=os.path.getmtime)[-1]
        ckpt_path = os.path.join(fold_dir, "checkpoints", "last.ckpt")
        if not os.path.exists(ckpt_path):
            ckpts = glob.glob(os.path.join(fold_dir, "checkpoints", "*.ckpt"))
            ckpt_path = ckpts[-1] if ckpts else None

        cfg_path = os.path.join(fold_dir, "config.yaml")
        if not os.path.exists(cfg_path):
            cfg_path = "model_config.yaml"

        config = read_config(cfg_path)

        # 2. Get In-Sample Validation metrics from evaluation JSON if already saved
