def generate_custom_trainer(config: dict) -> pl.Trainer:
    save_dir = config["experiment"]["save_dir"]
    os.makedirs(save_dir, exist_ok=True)

    callbacks = [
        ModelCheckpoint(
            dirpath=os.path.join(save_dir, "checkpoints"),
            save_last=True,
            save_top_k=3,
            monitor="val Thickness RMSE",
            mode="min",
            every_n_epochs=1,
        )
    ]

    if "swa_lrs" in config.get("optimizer", {}):
        callbacks.append(
            StochasticWeightAveraging(
                swa_lrs=config["optimizer"]["swa_lrs"],
                swa_epoch_start=config["optimizer"]["swa_epoch_start"],
                annealing_epochs=config["optimizer"]["swa_annealing_epochs"]
            )
        )

    loggers = [pl.loggers.CSVLogger(save_dir, name="csv_logs")]

    return pl.Trainer(
        accelerator=config["pl"]["accelerator"],
        devices=config["pl"]["devices"],
        max_epochs=config["pl"].get("max_epochs", 100),
        check_val_every_n_epoch=1,
        default_root_dir=save_dir,
        logger=loggers,
        callbacks=callbacks,
        log_every_n_steps=config["pl"].get("log_every_n_steps", 10)
    )

