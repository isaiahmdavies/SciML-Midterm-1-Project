        config["pl"]["accelerator"] = "gpu" if torch.cuda.is_available() else "cpu"
        config["pl"]["devices"] = [0] if torch.cuda.is_available() else "auto"
        config["optimizer"]["scheduler"] = "plateau"
        config["optimizer"]["weight_lr"] = 1e-3

