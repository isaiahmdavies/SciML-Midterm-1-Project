"""RMSE Error over time"""

import os
import glob
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

def plot_rmse_over_epochs(exp_dir="CV/allunmappedglaciers_notsurging/test1", glacier_id=None):
    # 1. Locate the latest metrics.csv file
    csv_candidates = sorted(
        glob.glob(os.path.join(exp_dir, "**", "csv_logs", "**", "metrics.csv"), recursive=True) +
        glob.glob(os.path.join(exp_dir, "**", "metrics.csv"), recursive=True),
        key=os.path.getmtime
    )

    if not csv_candidates:
        raise FileNotFoundError(f"No metrics.csv found under '{exp_dir}'.")

    if glacier_id:
        csv_candidates = [f for f in csv_candidates if glacier_id in f]
        if not csv_candidates:
            raise ValueError(f"No log matching glacier '{glacier_id}' found.")

    target_csv = csv_candidates[-1]
    run_name = os.path.basename(os.path.dirname(os.path.dirname(target_csv)))
    print(f"Reading logs from: {target_csv}")
    print(f"Plotting RMSE for: {run_name}")

    df = pd.read_csv(target_csv)
    if 'epoch' not in df.columns:
        raise KeyError("Expected 'epoch' column in metrics.csv.")

    epoch_df = df.groupby('epoch').mean(numeric_only=True)
    epochs = epoch_df.index.values

    # 2. Extract Validation RMSE
    val_rmse = None
    for col in ['val Thickness RMSE', 'val_thickness_rmse', 'val_rmse', 'val/Thickness_RMSE']:
        if col in epoch_df.columns:
            val_rmse = epoch_df[col].dropna()
            break

    # 3. Extract or compute Training RMSE
    # If raw_loss/thickness is logged (MSE on standardized thickness), convert to physical meters
    train_rmse = None
    for col in ['train Thickness RMSE', 'train_thickness_rmse', 'train_rmse']:
        if col in epoch_df.columns:
            train_rmse = epoch_df[col].dropna()
            break

    # Physical scaling factor fallback (~100 m standard deviation across Svalbard ice thickness)
    thickness_scale = 100.0
    cfg_candidates = glob.glob(os.path.join(os.path.dirname(os.path.dirname(target_csv)), "*.yaml"))
    if cfg_candidates:
        try:
            import yaml
            with open(cfg_candidates[0], 'r') as fp:
                cfg_data = yaml.safe_load(fp)
                if 'transformation_target_var' in cfg_data.get('ds', {}):
                    thickness_scale = float(cfg_data['ds']['transformation_target_var'][0])
        except Exception:
            pass

    if train_rmse is None and 'raw_loss/thickness' in epoch_df.columns:
        raw_thickness_mse = epoch_df['raw_loss/thickness'].values
        # Unscale RMSE: sqrt(MSE) * target_std
        train_rmse_vals = np.sqrt(np.maximum(raw_thickness_mse, 0.0)) * thickness_scale
        train_rmse = pd.Series(train_rmse_vals, index=epoch_df.index).dropna()

    # 4. Generate Plot
    plt.figure(figsize=(10, 6), dpi=150)

    # Training RMSE (dashed light blue)
    if train_rmse is not None and not train_rmse.empty:
        plt.plot(
            train_rmse.index.values,
            train_rmse.values,
            label='Train Thickness RMSE',
            color='#aec7e8',
            linestyle='--',
            linewidth=2.0,
            alpha=0.9
        )

    # Validation RMSE (solid prominent dark blue)
    if val_rmse is not None and not val_rmse.empty:
        plt.plot(
            val_rmse.index.values,
            val_rmse.values,
            label='Val Thickness RMSE [m]',
            color='#1f77b4',
            linestyle='-',
            linewidth=2.8,
            marker='o',
            markersize=3.5,
            zorder=10
        )

    # Benchmark reference: In-sample paper baseline (~30 m)
    plt.axhline(
        y=30.0,
        color='#2ca02c',
        linestyle=':',
        linewidth=1.8,
        label='Paper Baseline In-Sample RMSE (30 m)'
    )

    # PINN burn-in marker
    plt.axvline(x=10, color='#888888', linestyle=':', alpha=0.55, label='PINN Burn-In (Epoch 10)')

    plt.xlabel('Epoch', fontsize=11)
    plt.ylabel('Thickness RMSE [m]', fontsize=11)
    plt.title(f'Thickness RMSE Convergence Over Epochs\n({run_name})', fontsize=13)
    plt.grid(True, which='both', linestyle='--', alpha=0.35)
    plt.legend(bbox_to_anchor=(1.02, 1), loc='upper left', frameon=True, fontsize=10)
    plt.tight_layout()

    save_path = os.path.join(exp_dir, f"rmse_over_epochs_{run_name}.png")
    plt.savefig(save_path, bbox_inches='tight')
    plt.show()
    print(f"Plot saved to: {save_path}")

plot_rmse_over_epochs()