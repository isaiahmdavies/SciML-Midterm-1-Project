                test_ds = PL_GlacierDataset(eval_cfg)
                test_ds.setup('validate')
                val_loader = test_ds.val_dataloader()

                all_preds = []
                all_targets = []

                # Ensure scale factors exist
                t_scale = torch.tensor(test_ds.target_scaler.scale_[0], device=device)
