def plot_loss_weights(exp_dir="CV/allunmappedglaciers_notsurging", glacier_id=None):
    # 1. Locate the latest metrics.csv file
    search_paths = [
        os.path.join(exp_dir, "**", "csv_logs", "**", "metrics.csv"),
        os.path.join(exp_dir, "**", "metrics.csv"),
        "./checkpoints/**/metrics.csv"
    ]

    csv_files = []
    for pattern in search_paths:
        csv_files.extend(glob.glob(pattern, recursive=True))
    csv_files = sorted(list(set(csv_files)), key=os.path.getmtime)

    if not csv_files:
        raise FileNotFoundError(f"No metrics.csv found under {exp_dir}. Ensure training has run.")

    # Filter for a specific glacier fold if provided
    if glacier_id:
        csv_files = [f for f in csv_files if glacier_id in f]
        if not csv_files:
            raise ValueError(f"No log matching glacier '{glacier_id}' found.")

    latest_csv = csv_files[-1]
    run_dir = os.path.basename(os.path.dirname(os.path.dirname(latest_csv)))
    print(f"Reading weights from: {latest_csv}")

    df = pd.read_csv(latest_csv)
    if 'epoch' not in df.columns:
        raise KeyError("Expected 'epoch' column in metrics.csv.")

    # Average metrics per epoch
    epoch_df = df.groupby('epoch').mean(numeric_only=True)
    epochs = epoch_df.index.values

    loss_terms = ['thickness', 'pinn', 'depth_avg', 'vel_mag', 'neg_thick', 'smoothness']

    # 2. Extract precision weights (exp(-s_i))
    weights = {}
    for term in loss_terms:
        weight_col = f'weight/{term}'
        if weight_col in epoch_df.columns:
            weights[term] = epoch_df[weight_col].values

    if not weights:
        raise KeyError("No 'weight/*' columns found in metrics.csv.")

    # 3. Create Plots
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8), sharex=True, dpi=150)

    # Plot A: Effective Precision Weights (exp(-s_i))
    for term, w_vals in weights.items():
        ax1.plot(epochs, w_vals, label=term, lw=2)
    ax1.set_yscale('log')
    ax1.set_ylabel(r'Precision Weight $e^{-s_i} = \frac{1}{\sigma_i^2}$ (Log Scale)')
    ax1.set_title(f'Learned Loss Weights Across Epochs ({run_dir})', fontsize=12)
    ax1.grid(True, which='both', linestyle='--', alpha=0.5)
    ax1.legend(loc='center left', bbox_to_anchor=(1.01, 0.5), frameon=True)

    # Plot B: Learned Log-Variances (s_i)
    # Since precision = exp(-s_i), s_i = -ln(precision)
    for term, w_vals in weights.items():
        s_vals = -np.log(np.maximum(w_vals, 1e-12))
        ax2.plot(epochs, s_vals, label=term, lw=2)
    ax2.set_ylabel(r'Log-Variance $s_i = \ln(\sigma_i^2)$')
    ax2.set_xlabel('Epoch')
    ax2.set_title('Homoscedastic Uncertainty Parameter ($s_i$)', fontsize=12)
    ax2.grid(True, linestyle='--', alpha=0.5)
    ax2.legend(loc='center left', bbox_to_anchor=(1.01, 0.5), frameon=True)

    plt.tight_layout()
    plt.show()

