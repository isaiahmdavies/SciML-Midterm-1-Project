import torch
import torch.nn as nn
from model import PL_PINN

class CustomPINN(PL_PINN):
    def __init__(self, config):
        super().__init__(config)

        # The 6 loss terms tracked in the glacier PINN:
        # [thickness, pinn, depth_avg, vel_mag, neg_thick, smoothness]
        self.loss_names = [
            'thickness', 'pinn', 'depth_avg', 'vel_mag', 'neg_thick', 'smoothness'
        ]

        # Trainable log-variances: s_i = log(sigma_i^2)
        # exp(-s_i) serves as the precision weight (initially 1.0)
        self.log_vars = nn.Parameter(torch.zeros(len(self.loss_names), dtype=torch.float32))

    def training_step(self, train_batch, batch_idx):
        x, y, idx = train_batch
        x.requires_grad = True
        pred = self.model(x)

        # 1. Thickness loss on labeled radar points (masking NaNs)
        label_mask = ~torch.isnan(y[:, 0].squeeze())
        if torch.any(label_mask):
            thickness_loss = self.reconstruction_loss(pred[:, 0][label_mask], y[:, 0][label_mask])
        else:
            thickness_loss = torch.tensor(0.0, device=x.device)

        # 2. Physics-informed mass conservation loss (div(h * v) - apparent_mb)
        physics_loss = self.masscons_loss(
            pred, x, y, self.input_scale, self.input_mean, self.target_scale, self.target_mean
        )
        physics_loss_avg = torch.mean(physics_loss)

        # 3. Regularization & velocity constraints
        neg_thick = self.negative_thickness_loss(pred, self.target_scale, self.target_mean)
        smoothness = self.smooth_thickness_loss(pred, x, self.input_scale, self.target_scale)
        depth_avg = self.depth_averaged_velocity_loss(pred, x, self.input_scale, self.input_mean)
        vel_mag = self.vel_mag_loss(pred, x, self.input_scale, self.input_mean)

        unweighted_losses = {
            'thickness': thickness_loss,
            'pinn': physics_loss_avg,
            'depth_avg': depth_avg,
            'vel_mag': vel_mag,
            'neg_thick': neg_thick,
            'smoothness': smoothness
        }

        # 4. Multi-task loss combining data and PDE residuals
        overall_loss = torch.tensor(0.0, device=x.device)

        for i, name in enumerate(self.loss_names):
            loss_val = unweighted_losses[name]

            # Respect the burn-in epochs before enabling mass conservation
            if name == 'pinn' and self.current_epoch < self.burn_in:
                continue

            # Skip thickness loss if the current batch contains 0 labeled points
            if name == 'thickness' and torch.isnan(loss_val):
                continue

            precision = torch.exp(-self.log_vars[i])
            term_loss = precision * loss_val + 0.5 * self.log_vars[i]
            overall_loss = overall_loss + term_loss

            # Log learned weights and losses
            self.log(f'weight/{name}', precision.detach(), prog_bar=False)
            self.log(f'raw_loss/{name}', loss_val.detach(), prog_bar=False)

        self.log('train_overall_loss', overall_loss, prog_bar=True)
        return {"loss": overall_loss, "physics_loss": physics_loss, "idx": idx, "sample": x}

    def configure_optimizers(self):
        model_params = [p for n, p in self.named_parameters() if 'log_vars' not in n]

        optimizer = torch.optim.Adam([
            {'params': model_params, 'lr': self.learning_rate},
            {'params': [self.log_vars], 'lr': self.config['optimizer'].get('weight_lr', 1e-3)}
        ])

        scheduler_mode = self.config['optimizer'].get('scheduler', 'plateau')

        if scheduler_mode == 'plateau':
            scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
                optimizer,
                mode='min',
                factor=0.5,
                patience=5,
                min_lr=1e-6
            )
            return {
                "optimizer": optimizer,
                "lr_scheduler": {
                    "scheduler": scheduler,
                    "monitor": "val Thickness RMSE",
                    "interval": "epoch",
                    "frequency": self.config['pl'].get('check_val_every_n_epoch', 1),
                    "strict": False  # <-- Crucial: prevents crashing when validation runs less frequently
                }
            }
        elif scheduler_mode == 'cosine':
            scheduler = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(
                optimizer,
                T_0=10,
                T_mult=2,
                eta_min=1e-6
            )
            return {
                "optimizer": optimizer,
                "lr_scheduler": {
                    "scheduler": scheduler,
                    "interval": "epoch"
                }
            }

        return optimizer

