    plt.yscale('log')
    plt.xlabel('Epoch', fontsize=11)
    plt.ylabel('Effective Loss Magnitude (Log Scale)', fontsize=11)
    plt.title(f'Total Weighted Task Loss and Component Evolution\n({run_name})', fontsize=13)
    plt.grid(True, which='both', linestyle='--', alpha=0.35)
    plt.legend(bbox_to_anchor=(1.02, 1), loc='upper left', frameon=True, fontsize=10)
    plt.tight_layout()

    save_path = os.path.join(exp_dir, f"total_weighted_loss_fixed_{run_name}.png")
    plt.savefig(save_path, bbox_inches='tight')
