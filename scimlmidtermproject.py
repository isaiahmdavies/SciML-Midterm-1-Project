import os
import glob
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

def plot_logo_cv_losses(exp_dir="CV/allunmappedglaciers_notsurging", glacier_id=None):
    """
    Plots training loss trajectories and relative weighting dynamics for LOGO CV folds.

    Args:
        exp_dir (str): Base experiment directory where folds were saved.
        glacier_id (str, optional): Specific RGI ID (e.g. 'RGI60-07.01482') to plot.
                                    If None, plots the most recent fold.
    """
    # 1. Locate metrics.csv files in csv_logs
    search_pattern = os.path.join(exp_dir, "**", "csv_logs", "**", "metrics.csv")
    csv_files = sorted(glob.glob(search_pattern, recursive=True), key=os.path.getmtime)

    if not csv_files:
        # Fallback search if saved directly under checkpoints or fold root
        search_pattern = os.path.join(exp_dir, "**", "metrics.csv")
        csv_files = sorted(glob.glob(search_pattern, recursive=True), key=os.path.getmtime)

    if not csv_files:
        raise FileNotFoundError(f"No metrics.csv files found under '{exp_dir}'. Ensure at least one fold has run.")

    # Filter by specific glacier if requested
    if glacier_id:
        target_files = [f for f in csv_files if glacier_id in f]
        if not target_files:
            raise ValueError(f"No log files found matching glacier ID '{glacier_id}'. Available runs: {csv_files}")
        selected_csv = target_files[-1]
    else:
        selected_csv = csv_files[-1]

    # Extract fold/run title from folder name
    run_name = os.path.basename(os.path.dirname(os.path.dirname(selected_csv)))
    if "csv_logs" in run_name:
        run_name = os.path.basename(os.path.dirname(os.path.dirname(os.path.dirname(selected_csv))))

    print(f"Loading metrics from: {selected_csv}")
    print(f"Visualizing fold: {run_name}")

    df = pd.read_csv(selected_csv)

    # Group by epoch to compute epoch-averaged step metrics
    if 'epoch' not in df.columns:
        raise KeyError("Expected 'epoch' column in metrics.csv.")
    epoch_df = df.groupby('epoch').mean(numeric_only=True)

    loss_terms = ['thickness', 'pinn', 'depth_avg', 'vel_mag', 'neg_thick', 'smoothness']

    # 2. Extract raw losses and effective weighted losses: L_eff = precision * L_raw
    raw_df = pd.DataFrame(index=epoch_df.index)
    weighted_df = pd.DataFrame(index=epoch_df.index)
    weights_df = pd.DataFrame(index=epoch_df.index)

    for term in loss_terms:
        raw_col = f'raw_loss/{term}'
        weight_col = f'weight/{term}'

        if raw_col in epoch_df.columns:
            raw_df[term] = epoch_df[raw_col]
            if weight_col in epoch_df.columns:
                weights_df[term] = epoch_df[weight_col]
                weighted_df[term] = epoch_df[raw_col] * epoch_df[weight_col]
            else:
                weighted_df[term] = epoch_df[raw_col]
        else:
            raw_df[term] = 0.0
            weighted_df[term] = 0.0

    # Calculate relative percentages for each epoch
    row_sums = weighted_df.sum(axis=1).replace(0, 1.0)
    relative_df = (weighted_df.div(row_sums, axis=0)) * 100.0

    # 3. Create composite figure
    fig, axes = plt.subplots(3, 1, figsize=(11, 13), sharex=True, dpi=150)
    epochs = epoch_df.index.values

    # Plot A: Absolute Raw Losses (Unweighted PDE and Data terms)
    for term in loss_terms:
        if raw_df[term].max() > 0:
            axes[0].plot(epochs, raw_df[term], label=f'{term}', lw=1.8)
    axes[0].set_yscale('log')
    axes[0].set_ylabel('Raw Loss Magnitude (Log)')
    axes[0].set_title(f'Training Convergence: {run_name} — Raw Component Losses', fontsize=12)
    axes[0].grid(True, which="both", linestyle='--', alpha=0.4)
    axes[0].legend(loc='center left', bbox_to_anchor=(1.01, 0.5), frameon=True)

    # Plot B: Learned Precision Weights (exp(-s_i))
    for term in loss_terms:
        if term in weights_df.columns and weights_df[term].max() > 0:
            axes[1].plot(epochs, weights_df[term], label=f'weight ({term})', lw=1.8, linestyle='--')
    axes[1].set_yscale('log')
    axes[1].set_ylabel('Trainable Weight $1/\\sigma^2$ (Log)')
    axes[1].set_title('Evolution of Learned Homoscedastic Weights ($e^{-s_i}$)', fontsize=12)
    axes[1].grid(True, which="both", linestyle='--', alpha=0.4)
    axes[1].legend(loc='center left', bbox_to_anchor=(1.01, 0.5), frameon=True)

